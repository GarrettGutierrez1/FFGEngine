#ifndef FFG_ENGINE_STATE_H
#define FFG_ENGINE_STATE_H

#include <SDL3/SDL.h>

namespace FFG::ENGINE {

class Engine;

/// @class State.
///
/// @brief A pure virtual class for defining the application's state.
class State {
private:
    Engine *engine;

public:
    /// @brief Constructor.
    ///
    /// @param engine The engine the state belongs to.
    explicit State(Engine *engine) : engine(engine) {}
    virtual ~State() = default;
    State(const State &) = delete;
    State &operator=(const State &) = delete;
    State(State &&) = delete;
    State &operator=(State &&) = delete;

    /// @brief Gets the engine the state belongs to.
    ///
    /// @return The engine.
    Engine *get_engine() { return engine; }

    /// @brief Initializes the state.
    ///
    /// @details This is called when the engine is initialized and when the engine swaps states. By convention this
    /// should do little more than initialize any objects or memory that the state needs.
    ///
    /// @see StateManager#set_next_state()
    ///
    /// @warning This should never call StateManager#set_next_state().
    virtual void init() = 0;

    /// @brief Deinitializes the state.
    ///
    /// @details This is called when the engine swaps states and when the is engine deinitialized. By convention this
    /// should do little more than free any memory that the state is using.
    ///
    /// @see StateManager#set_next_state().
    ///
    /// @warning This should never call StateManager#set_next_state(), Engine#set_quit(), or Engine#set_error().
    virtual void exit() = 0;

    /// @brief Handles an event.
    ///
    /// @details This is called whenever there is an event to be handled. Events are handled in batches between calls to
    /// Engine#AppIterate(). The return value is intended to indicate if the event has been handled by the state and
    /// that no further processing of the event is necessary. However, it is ignored by the engine. It is useful if for
    /// example you want to create state hierarchies where a parent state only handles an event if its child states do
    /// not. Not all events generated by SDL are passed to the state as some are handled by the engine itself.
    ///
    /// @param event The event to handle.
    ///
    /// @return `true` if the event has been handled, otherwise `false`.
    virtual bool handle(SDL_Event *event) = 0;

    /// @brief Updates the state.
    ///
    /// @details This is called once per call to Engine#AppIterate(), just before #render. This is called once per drawn
    /// frame, so if you want your application to perform multiple logical updates per frame, that should be handled by
    /// the state.
    virtual void update() = 0;

    /// @brief Renders the state.
    ///
    /// @details This is called once per call to Engine#AppIterate(), just after #update. All drawing should happen here
    /// and only here. The engine automatically handles clearing the screen buffer immediately before rendering, and
    /// swapping the screen buffers immediately after rendering.
    virtual void render() = 0;
};

} // namespace FFG::ENGINE

#endif // FFG_ENGINE_STATE_H
